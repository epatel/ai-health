"""CMake adapter: units (definitions, top-level blocks), metrics, excludes."""

import subprocess
from pathlib import Path

import pytest
from helpers import findings_of

from aihealth.config import Config
from aihealth.engine import scan
from aihealth.lang import adapter_for, is_supported, parse_file, parse_source
from aihealth.lang.base import is_generated
from aihealth.metrics import function_metrics

FIXTURE = Path(__file__).parent / "fixtures" / "CMakeLists.txt"


def metrics(src: str, path: str = "x.cmake") -> dict:
    module = parse_source(src.encode(), path)
    assert module.error_count == 0
    adapter = adapter_for(path)
    return {f.qualname: function_metrics(f, adapter) for f in module.all_functions()}


@pytest.mark.parametrize(
    ("path", "supported"),
    [
        ("CMakeLists.txt", True),
        ("sub/dir/CMakeLists.txt", True),
        ("cmake/FindFoo.cmake", True),
        ("notes.txt", False),
    ],
)
def test_registry(path, supported):
    assert is_supported(path) is supported
    if supported:
        assert adapter_for(path).language == "cmake"


def test_fixture_units():
    fns = parse_file(FIXTURE).all_functions()
    assert [(f.qualname, f.kind) for f in fns] == [
        ("if(WIN32 AND NOT MINGW)", "conditional"),
        ("sample_add_library", "function"),
        ("sample_warnings", "macro"),
        ("foreach(tool IN ITEMS cli gui)", "loop"),
        ("while(i LESS 3)", "loop"),
        ("if(SAMPLE_TESTS)", "conditional"),
    ]
    params = next(f for f in fns if f.qualname == "sample_add_library").params
    assert [p.name for p in params] == ["name"]


def test_plain_commands_are_not_units_and_nested_definitions_are():
    src = """
set(A 1)
add_library(core a.c)
if(UNIX)
  function(unix_only x)
    message(${x})
  endfunction()
endif()
"""
    assert list(metrics(src)) == ["if(UNIX)", "unix_only"]


GOLDEN = """
function(nested_loops items)
  foreach(item IN LISTS items)
    foreach(part IN LISTS item)
      if(part STREQUAL "x")
        continue()
      endif()
    endforeach()
  endforeach()
endfunction()

function(chain value)
  if(value LESS 0)
    set(r negative)
  elseif(value EQUAL 0)
    set(r zero)
  elseif(value LESS 10)
    set(r small)
  else()
    set(r large)
  endif()
endfunction()

function(sequences a b c d e f)
  if(a AND b AND c OR d OR e AND f)
    message(yes)
  endif()
endfunction()

function(countdown n)
  if(n GREATER 0)
    math(EXPR m "${n} - 1")
    countdown(${m})
  endif()
endfunction()

function(waiting)
  set(i 0)
  while(i LESS 3 AND NOT done)
    math(EXPR i "${i} + 1")
  endwhile()
endfunction()

MACRO(LEGACY x)
  IF(x)
    MESSAGE(${x})
  ENDIF()
ENDMACRO()
"""

# qualname, cyclomatic, cognitive, max nesting
GOLDEN_EXPECTED = [
    ("nested_loops", 4, 6, 3),  # foreach +1, foreach +2, if +3
    ("chain", 4, 4, 1),  # if, two elseif, else: +1 each
    ("sequences", 7, 4, 1),  # if +1; AND/OR sequences +3, as SonarSource counts them
    ("countdown", 2, 2, 1),  # recursion +1
    ("waiting", 3, 2, 1),  # while +1, AND +1
    ("LEGACY", 2, 1, 1),  # upper-case commands parse the same
]


@pytest.mark.parametrize(("qualname", "cyc", "cog", "nest"), GOLDEN_EXPECTED)
def test_cmake_complexity(qualname, cyc, cog, nest):
    m = metrics(GOLDEN)[qualname]
    assert (m.cyclomatic, m.cognitive, m.max_nesting) == (cyc, cog, nest)


def test_conditions_are_conditions():
    m = metrics(GOLDEN)
    assert [(b.operators, b.is_condition) for b in m["sequences"].bool_exprs] == [(5, True)]
    assert [(b.operators, b.is_condition) for b in m["waiting"].bool_exprs] == [(1, True)]


def test_fixture_metrics():
    fns = {f.qualname: f for f in parse_file(FIXTURE).all_functions()}
    adapter = adapter_for(FIXTURE)
    top = function_metrics(fns["if(WIN32 AND NOT MINGW)"], adapter)
    assert (top.cyclomatic, top.cognitive) == (4, 4)  # if, AND, elseif, else
    lib = function_metrics(fns["sample_add_library"], adapter)
    assert (lib.cyclomatic, lib.cognitive, lib.max_nesting) == (6, 7, 2)


def test_copied_commands_get_cmake_hint():
    block = "".join(
        f"  target_compile_options(t{i} PRIVATE -Wall -Wextra -Werror)\n" for i in range(8)
    )
    src = f"function(a)\n{block}endfunction()\n\nfunction(b)\n{block}endfunction()\n"
    found = findings_of(src, "x.cmake", "code_duplication")
    assert found and "function()" in found[0].hint


def test_cmake_generated_files_are_recognised():
    assert is_generated(b"# CMake generated Testfile for\n# Source directory: /x\n")
    assert is_generated(b"# Generated by CMake\n\nif(...)\n")
    assert not is_generated(FIXTURE.read_bytes())


def test_scan_skips_build_dirs_deps_and_templates(tmp_path):
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    (tmp_path / "CMakeLists.txt").write_text("project(x)\n")
    for skipped in ("cmake-build-debug", "_deps/zlib-src", "CMakeFiles"):
        (tmp_path / skipped).mkdir(parents=True)
        (tmp_path / skipped / "CMakeLists.txt").write_text("project(y)\n")
    (tmp_path / "config.h.cmake").write_text("#cmakedefine HAVE_X @HAVE_X@\n")
    assert [f.path for f in scan(tmp_path, Config()).files] == ["CMakeLists.txt"]
