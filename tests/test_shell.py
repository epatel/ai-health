def test_functions_are_global_and_blocks_are_named_by_their_first_line():
    src = """if command -v gdate >/dev/null; then
    now() { gdate +%s%N; }
else
    now() { date +%s; }
fi
outer() {
    inner() { echo; }
}
while read -r line; do
    echo "$line"
done < input.txt
case "$1" in
    a) echo a ;;
esac
[ -n "$X" ] && helper() { echo; }
echo done
"""
    assert units(src) == [
        "if command -v gdate >/dev/null conditional",
        "now function",
        "now#2 function",
        "outer function",
        "inner function",
        "while read -r line loop",
        'case "$1" in case',
        "helper function",
    ]


def test_case_patterns_with_quoted_globs_parse():
    """`--only=*' '*)` made the grammar lose the rest of the file."""
    src = """main() {
    case "$1" in
        --only=*' '*) echo spaced ;;
        --*) echo flag ;;
    esac
}
after() {
    echo ok
}
"""
    module = parse_source(src.encode(), "x.sh")
    assert not module.root.has_error
    assert units(src) == ["main function", "after function"]


# --- golden metrics ----------------------------------------------------------------

SONAR = """sum_of_primes() {
    local total=0
    for ((i = 1; i <= $1; ++i)); do
        for ((j = 2; j < i; ++j)); do
            if (( i % j == 0 )); then
                continue 2
            fi
        done
        total=$((total + i))
    done
    echo "$total"
}

get_words() {
    case "$1" in
        1) echo one ;;
        2) echo "a couple" ;;
        3) echo "a few" ;;
        *) echo lots ;;
    esac
}

seq_test() {
    [[ $a && $b && $c || $d || $e && $f ]]
}

seq_list() {
    a && b && c || d || e && f
}

fact() {
    if (( $1 <= 1 )); then
        echo 1
        return
    fi
    echo $(( $1 * $(fact $(( $1 - 1 ))) ))
}

else_if() {
    if [ "$1" -gt 1 ]; then
        echo 1
    elif [ "$1" -gt 0 ]; then
        echo 2
    else
        echo 3
    fi
}

loops() {
    until false; do
        while true; do
            break
        done
    done
}
"""

# qualname, cyclomatic, cognitive, max nesting
SONAR_EXPECTED = [
    ("sum_of_primes", 4, 7, 3),  # for +1, for +2, if +3, `continue 2` +1
    ("get_words", 4, 1, 1),  # `*)` is not a path of its own
    ("seq_test", 6, 3, 0),
    ("seq_list", 6, 3, 0),
    ("fact", 2, 2, 1),  # recursion +1
    ("else_if", 3, 3, 1),
    ("loops", 3, 3, 2),  # until +1, while +2; a plain `break` adds nothing
]


@pytest.mark.parametrize(("qualname", "cyc", "cog", "nest"), SONAR_EXPECTED)
def test_shell_complexity(qualname, cyc, cog, nest):
    m = metrics(SONAR)[qualname]
    assert (m.cyclomatic, m.cognitive, m.max_nesting) == (cyc, cog, nest)


def test_fixture_metrics():
    path = FIXTURES / "sample.sh"
    fns = {f.qualname: f for f in parse_file(path).all_functions()}
    build = function_metrics(fns["build"], adapter_for(path))
    # for +1, if +2, `&&` +1, `|| die` +1, elif +1, else +1, `cd && make` +1,
    # c-style for +1, until +2, arithmetic ternary +1
    assert (build.cyclomatic, build.cognitive, build.max_nesting) == (10, 12, 2)


