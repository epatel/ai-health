@pytest.mark.parametrize("line", ROUTES.strip().splitlines())
def test_routing_by_extension_and_shebang(line):
    path, rest = line.split(" | ")
    head, expected = rest.rsplit("=> ", 1)
    assert is_supported(path, head.strip().encode() + b"\n") is (expected == "yes")


def test_a_shebang_script_is_bash_and_needs_its_head():
    assert not is_supported("bin/deploy")  # without content it can't be told
    module = parse_source(b"#!/bin/sh\nf() { :; }\n", "bin/deploy")
    assert module.language == "bash"
    assert [f.qualname for f in module.all_functions()] == ["f"]


def test_scan_and_file_check_find_extensionless_scripts(tmp_path):
    (tmp_path / "bin").mkdir()
    (tmp_path / "bin/deploy").write_text("#!/usr/bin/env bash\nmain() {\n  echo hi\n}\n")
    (tmp_path / "bin/tool").write_text("#!/usr/bin/env python3\nprint('hi')\n")
    (tmp_path / "LICENSE").write_text("MIT\n")
    result = scan(tmp_path, Config())
    assert [f.path for f in result.files] == ["bin/deploy"]
    assert is_supported_file(tmp_path / "bin/deploy")
    assert not is_supported_file(tmp_path / "bin/tool")


def test_delta_scores_extensionless_scripts_by_content(tmp_path):
    git(tmp_path, "init", "-q", "-b", "main")
    (tmp_path / "deploy").write_text("#!/bin/bash\nmain() {\n  echo hi\n}\n")
    (tmp_path / "notes").write_text("plain text\n")
    git(tmp_path, "add", ".")
    git(tmp_path, "commit", "-q", "-m", "init")
    nested = "  if a; then\n    for x in y; do\n      if b; then\n        while c; do :; done\n"
    (tmp_path / "deploy").write_text(
        f"#!/bin/bash\nmain() {{\n{nested}      fi\n    done\n  fi\n}}\n"
    )
    (tmp_path / "notes").write_text("more text\n")
    result = run_delta(tmp_path, Config())
    assert [f.path for f in result.files] == ["deploy"]
    assert result.skipped == []  # `notes` is silently not a script


def test_generated_scripts_are_skipped():
    assert is_generated(b"#! /bin/sh\n# Generated by GNU Autoconf 2.71 for x 1.0.\n")
    assert is_generated(b"#! /bin/sh\n# Generated by configure.\n")


