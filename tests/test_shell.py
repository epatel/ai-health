# path | first line => module language
LANGUAGES = """
a.sh | #!/bin/bash => bash
a.zsh | => zsh
a.zsh-theme | => zsh
a.sh | #!/bin/zsh => zsh
bin/tool | #!/usr/bin/env zsh => zsh
_docker | #compdef docker => zsh
bin/tool | #!/bin/sh => bash
"""


@pytest.mark.parametrize("line", LANGUAGES.strip().splitlines())
def test_zsh_files_use_the_zsh_grammar(line):
    path, rest = line.split(" | ")
    head, expected = rest.rsplit("=> ", 1)
    source = head.strip().encode() + b"\nf() { :; }\n"
    assert parse_source(source, path).language == expected


def test_zsh_units():
    src = """() {
    local x
    for k v in ${(kv)m}; do echo $k; done
}
repeat 3 { echo }
for f (a b) { echo $f }
select x in a b; do break; done
function show { echo }
"""
    assert units(src, "x.zsh") == [
        "(anonymous) function",
        "repeat 3 { echo } loop",
        "for f (a b) { echo $f } loop",
        "select x in a b; do break; done loop",
        "show function",
    ]


ZSH = """loops() {
    repeat 3 {
        for x (a b) {
            [[ -n $x ]] && echo $x
        }
    }
}

guarded() {
    { echo } always { echo done }
}
"""


def test_zsh_complexity():
    got = {q: (m.cyclomatic, m.cognitive, m.max_nesting) for q, m in metrics(ZSH, "x.zsh").items()}
    # repeat +1, for +2, `&&` +1; `always` is a `finally`, no increment
    assert got == {"loops": (4, 4, 2), "guarded": (1, 0, 0)}


def test_prepare_zsh_keeps_offsets():
    src = b"for k v in a; do :; done\nx=${a//b/)} y=${${c}/d/${e}(f)} z=${g/h/$(i)}\n"
    out = prepare_zsh(src)
    assert len(out) == len(src)
    assert out.splitlines() == [
        b"for k   in a; do :; done",
        b"x=${a//b/_} y=${${c}/d/${e}_f_} z=${g/h/$(i)}",
    ]


# the zsh grammar never returns on this one (and grows to gigabytes)
HANGS = rb"x=${${${(q)a}/#(#b)${(q)H}(|\/*)/'~'$m[1]}//\%/%%}"


def test_a_zsh_parse_that_never_ends_falls_back_to_bash():
    assert not _finishes(tslp.get_parser("zsh"), HANGS)
    assert _finishes(tslp.get_parser("zsh"), b"echo hi\n")
    module = parse_source(HANGS + b"\nf() {\n  echo\n}\n", "x.zsh")
    assert module.language == "zsh"
    assert [f.qualname for f in module.all_functions()] == ["f"]


def test_the_tree_that_loses_fewer_lines_wins():
    src = b'x="${a=" "}"\nf() { :; }\n'  # the zsh grammar loses line 1
    assert lost_lines(tslp.get_parser("zsh").parse(src).root_node) == 1
    assert lost_lines(ZshParser().parse(src).root_node) == 0
