def metrics(src: str, path: str = "x.sh") -> dict:
    module = parse_source(src.encode(), path)
    assert not module.root.has_error
    adapter = adapter_for(path, head=src.encode())
    return {f.qualname: function_metrics(f, adapter) for f in module.all_functions()}


def units(src: str, path: str = "x.sh") -> list[str]:
    return [f"{f.qualname} {f.kind}" for f in parse_source(src.encode(), path).all_functions()]


